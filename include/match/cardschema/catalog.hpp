namespace match::cardschema {

// INFO: how many decks one mod may declare, and how many the loaded mods may
// declare together. The loader reports a mod past the first limit and the whole
// scan past the second before it expands anything.
inline constexpr std::size_t kMaximumDecksPerMod = 64;
inline constexpr std::size_t kMaximumDecksTotal = 256;

// INFO: how many schema diagnostics one loader report shows before it adds a
// single "too many schema errors" marker. The cap counts schema diagnostics
// only, so a mod with many ordinary errors still shows its schema report.
inline constexpr std::size_t kMaximumSchemaDiagnostics = 100;

// INFO: the message of the single diagnostic that ends a capped cardschema
// report; a caller that converts such a report skips it and adds its own
// marker instead of passing two truncation lines through.
inline constexpr const char* kSchemaTruncationMarker = "more errors not shown";

// INFO: one engine card generated by expanding a concrete template over the
// members of its slots.
struct GeneratedCard {
    std::string kind_id;                 // "uni:red_5"
    std::string host_mod;                // namespace of the template
    std::string template_id;             // "uni:numbered"
    std::string title;                   // "Red 5"
    json face;                           // template face with placeholders filled
    std::vector<std::string> tags;       // template tags, then member tags in slot order
    std::map<std::string, std::string> slot_members;   // slot name -> member identifier
    std::vector<std::string> requires_mods;            // mods of the members, minus host_mod
    json legacy_entry;                   // the old card-file shape ParseCardEntry reads
};

struct CatalogResult {
    std::vector<GeneratedCard> cards;    // sorted by kind_id
    std::vector<Diagnostic> diagnostics;
};

// INFO: expands every concrete template of every mod over the members of all
// mods, in load order. An abstract template generates nothing; a template with
// no slots generates one card; cross-product entries that are the same card by
// SameCard collapse into one. A template exceeding the 4096 generated kinds of
// its host mod is an error reported before any card is allocated.
//
// INFO: `extends` is walked for every concrete template with BuildExtendsChain,
// so a missing parent or a cycle is a diagnostic; the chain is NOT applied to
// the expansion. The spec inherits only `slot_order` and `contribute` through
// `extends`, and the migrated data repeats the other fields (tags, face,
// formats, behavior) on every concrete template, so the expansion uses the
// template's own slots and fields alone.
CatalogResult ExpandCards(const std::vector<ModSchema>& mods);

// INFO: one deck expanded into the engine cards it deals. `cards` merges the
// copies of one kind from every entry and keeps the order the kinds were first
// dealt in.
struct ExpandedDeck {
    std::string deck_id;
    std::string name;
    std::vector<std::string> mods;                    // from DeckSpec.mods
    std::vector<std::pair<std::string, int>> cards;   // kind_id -> count, first-seen order
    int total = 0;
    std::vector<Diagnostic> diagnostics;
};

// INFO: expands the deck `deck_id` of `mods` over the members of the active
// mods. `active_mods` filters which loaded mods contribute members and
// templates; an empty set means every loaded mod is active. `settings` holds
// the `@settings.<name>` values of a `copies` expression.
//
// INFO: a selector picks the members of the attribute bound to its slot; a slot
// the entry does not name selects every member. A selector that matches no
// member adds no cards and is not an error, except an `identifiers` entry that
// names no member of the attribute. A `copies` expression is checked against a
// Schema whose settings are all ints and evaluated with only `@settings`
// readable. The running total is checked against the deck limit before a card
// is built.
//
// INFO: on any error the caller must not read `cards`/`total`; expansion may
// stop early and both describe only the entries seen before the error.
//
// INFO: `product` over a template whose slots form a symmetric pair counts both
// orders of the pair ("red_blue" and "blue_red"); use `unique_pairs` to avoid
// the duplicate.
//
// INFO: every call expands the catalog of the active mods again, so one call
// per deck costs one full catalog expansion. Prefer the `CatalogResult` overload
// below when the caller already holds the expanded catalog.
ExpandedDeck ExpandDeck(const std::vector<ModSchema>& mods, const std::string& deck_id,
                        const std::set<std::string>& active_mods,
                        const std::map<std::string, int64_t>& settings);

// INFO: the same expansion over an already-expanded catalog. `catalog` must be
// `ExpandCards` of a mod list that contains every mod of `mods`; the deck costs
// O(deck) instead of O(catalog) because the generated cards are only filtered
// by the active set, not built again.
ExpandedDeck ExpandDeck(const CatalogResult& catalog, const std::vector<ModSchema>& mods,
                        const std::string& deck_id,
                        const std::set<std::string>& active_mods,
                        const std::map<std::string, int64_t>& settings);

}  // namespace match::cardschema
